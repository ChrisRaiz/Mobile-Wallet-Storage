// Regenerates src/lib/pass-images.ts from the PNG files in pass-assets/.
// Run with `npm run embed-images` after changing a pass image.
//
// The images are embedded in the code, rather than read from disk at request time,
// so they're always included in the server build whichever folder it runs from.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const assetDir = fileURLToPath(new URL("../pass-assets/", import.meta.url));
const outFile = fileURLToPath(new URL("../src/lib/pass-images.ts", import.meta.url));

const names = readdirSync(assetDir).filter((name) => name.endsWith(".png")).sort();
if (!names.includes("icon.png")) throw new Error("pass-assets/icon.png is required by Apple Wallet.");

const entries = names
  .map((name) => `  "${name}": "${readFileSync(assetDir + name).toString("base64")}",`)
  .join("\n");

writeFileSync(
  outFile,
  `// Generated by scripts/embed-pass-images.mjs from pass-assets/. Do not edit by hand.\n` +
    `// Run \`npm run embed-images\` after changing an image.\n\n` +
    `const BASE64: Record<string, string> = {\n${entries}\n};\n\n` +
    `/** The images bundled into every Apple Wallet pass, keyed by file name. */\n` +
    `export function passImages(): Record<string, Buffer> {\n` +
    `  return Object.fromEntries(Object.entries(BASE64).map(([name, data]) => [name, Buffer.from(data, "base64")]));\n` +
    `}\n`,
);
console.log(`Embedded ${names.length} images into src/lib/pass-images.ts`);
